/*
 * Report export: full JSON (tokens + diagnostics + meta) and an
 * Arden-MLM-flavoured YAML summary for hand-off / documentation.
 */

function download(filename, text, mime) {
  const blob = new Blob([text], { type: mime + ';charset=utf-8' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  URL.revokeObjectURL(a.href);
}

export function exportJson(report, meta, code) {
  const doc = {
    tool: 'HELIX Clinical Rule IDE',
    exportedAt: new Date().toISOString(),
    rule: {
      name: meta.ruleName,
      intent: meta.intent,
      trigger: meta.trigger,
      urgency: meta.urgency,
      terminology: meta.terminology.map((t) => ({ system: t.system, code: t.code })),
      sourceLines: code.split('\n').length,
    },
    analysis: report,
  };
  download(`${meta.ruleName}.analysis.json`, JSON.stringify(doc, null, 2), 'application/json');
}

function yamlEscape(s) {
  if (s == null) return '""';
  const str = String(s);
  return /[:#{}\[\],&*?|>%@`'"]|^\s|\s$/.test(str) || str === ''
    ? '"' + str.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'
    : str;
}

export function exportYaml(report, meta, code) {
  const stats = report.stats;
  const lines = [];
  lines.push('# HELIX clinical decision rule — Arden-style summary');
  lines.push('# Generated by HELIX Clinical Rule IDE');
  lines.push('mlm:');
  lines.push(`  name: ${yamlEscape(meta.ruleName)}`);
  lines.push('  type: medical_logical_module');
  lines.push(`  description: ${yamlEscape(meta.intent)}`);
  lines.push('  library:');
  lines.push(`    trigger: ${yamlEscape(meta.trigger)}`);
  lines.push(`    urgency: ${yamlEscape(meta.urgency)}`);
  if (meta.terminology.length) {
    lines.push('    terminology:');
    for (const t of meta.terminology) {
      lines.push(`      - system: ${t.system}`);
      lines.push(`        code: ${yamlEscape(t.code)}`);
    }
  }
  lines.push('  data:');
  lines.push('    variables:');
  const letRe = /\blet\s+([A-Za-z_]\w*)\s*:?=\s*("[^"]*"|-?\d+\.?\d*)/g;
  let m;
  while ((m = letRe.exec(code)) !== null) {
    lines.push(`      - name: ${m[1]}`);
    lines.push(`        value: ${yamlEscape(m[2])}`);
  }
  const bindRe = /\bbind\s+([A-Za-z_]\w*)\s*[:=]?=\s*([A-Za-z_][\w.]*)/g;
  while ((m = bindRe.exec(code)) !== null) {
    lines.push(`      - name: ${m[1]}`);
    lines.push(`        source: ${m[2]}`);
  }
  lines.push('  logic:');
  lines.push('    if:');
  lines.push(`      expression: ${yamlEscape((code.match(/\bwhen\b([^:]*):/) || [, ''])[1].trim())}`);
  lines.push('    then:');
  const alertMsg = code.match(/\balert\s*:\s*"([^"]*)"(?:\s*,\s*"([^"]*)")?/);
  if (alertMsg) {
    lines.push(`      message: ${yamlEscape(alertMsg[1])}`);
    if (alertMsg[2]) lines.push(`      level: ${yamlEscape(alertMsg[2])}`);
  }
  const sup = code.match(/\bsuppress\s*:?\s*(?:repeat_of\s*:\s*[A-Za-z_]\w*\s+)?within\s+(\d+\s*[A-Za-z]+)/);
  if (sup) lines.push(`      suppress_within: ${yamlEscape(sup[1])}`);
  lines.push('  validation:');
  lines.push(`    status: ${stats.valid ? 'valid' : 'invalid'}`);
  lines.push(`    lexical_errors: ${stats.lexicalErrors}`);
  lines.push(`    syntax_errors: ${stats.syntaxErrors}`);
  lines.push(`    token_count: ${stats.tokens}`);
  lines.push(`    rule_count: ${stats.rules}`);

  download(`${meta.ruleName}.summary.yaml`, lines.join('\n'), 'text/yaml');
}
